def parse(path):
    raw = open(path, "rb").read()
    for enc in ("utf-8-sig", "utf-8", "gb18030", "cp1252"):
        try:
            return ET.fromstring(raw.decode(enc))
        except Exception:
            pass
    raise RuntimeError("parse fail: " + path)


def write(root, path):
    ET.indent(root, space="  ")
    data = ET.tostring(root, encoding="unicode")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write('<?xml version="1.0" encoding="UTF-8"?>\n' + data + "\n")


def main():
    for fn, mapping in FIX.items():
        path = os.path.join(ROOT, fn)
        root = parse(path)
        blocks = {}
        for b in root.findall("./briefings/block"):
            blocks[b.get("id")] = b
        old_chn = {}
        for bid, b in blocks.items():
            langs = {l.get("code"): l for l in b.findall("lang")}
            cn = langs.get("CHN")
            if cn is not None:
                old_chn[bid] = copy.deepcopy(cn)
        n = 0
        for dest, (kind, val) in mapping.items():
            if dest.endswith("_t1"):  # 特殊: 只替换第 2 个 text(索引1)
                base = dest[:-3]
                b = blocks.get(base)
                if b is None:
                    continue
                langs = {l.get("code"): l for l in b.findall("lang")}
                cn = langs.get("CHN")
                texts = [c for c in cn if c.tag == "text"]
                if len(texts) >= 2:
                    texts[1].text = val[0]
                    n += 1
                continue
            b = blocks.get(dest)
            if b is None:
                print("[!] %s: 无 block %s" % (fn, dest)); continue
            langs = {l.get("code"): l for l in b.findall("lang")}
            cn = langs.get("CHN")
            if cn is None:
                print("[!] %s: block %s 无 CHN" % (fn, dest)); continue
            if kind == "COPY":
                src = old_chn.get(val)
                if src is None:
                    print("[!] %s: 旧 block %s 无 CHN" % (fn, val)); continue
                cn[:] = copy.deepcopy(list(src))
            else:
                new_els = []
                for t in val:
                    el = ET.Element("text")
                    el.text = t
                    el.tail = "\n        "
                    new_els.append(el)
                cn[:] = new_els
            n += 1
        write(root, path)
        print("OK   %s (%d 处)" % (fn, n))


if __name__ == "__main__":
    main()
